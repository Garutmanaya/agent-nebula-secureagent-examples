#!/usr/bin/env python3
"""Generate Nginx/ngrok configuration from the Nebula example manifest."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

REPO = Path(__file__).resolve().parents[1]


def endpoints() -> list[tuple[str, int]]:
    catalog = json.loads((REPO / 'examples.json').read_text())
    result = []
    for example_id, item in catalog.items():
        if not item['directory'].startswith('examples-nebula/'):
            continue
        for cfg in sorted((REPO / item['directory'] / 'config').glob('*.conf')):
            if cfg.name not in {'a2aserver.conf', 'provider-server.conf', 'orchestrator-server.conf'}:
                continue
            match = re.search(r'^port\s*=\s*(\d+)\s*$', cfg.read_text(), re.M)
            if not match:
                raise SystemExit(f'No server port in {cfg}')
            port = int(match.group(1))
            suffix = '' if cfg.name == 'a2aserver.conf' else '-' + cfg.stem.replace('-server', '')
            result.append((f'{example_id}{suffix}', port))
    if not result:
        raise SystemExit('No Nebula example server configurations found')
    if len(set(x[0] for x in result)) != len(result):
        raise SystemExit('Duplicate public route names')
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--domain', required=True, help='Assigned ngrok domain (hostname only)')
    parser.add_argument('--output', type=Path, required=True, help='Directory for generated configuration')
    parser.add_argument('--ca-file', type=Path, required=True, help='CA bundle trusted for local HTTPS agent servers')
    parser.add_argument('--upstream-tls-name', default='localhost', help='SAN name on local HTTPS server certificates')
    parser.add_argument('--listen', type=int, default=8080)
    args = parser.parse_args()
    domain = args.domain.strip()
    if urlsplit('https://' + domain).hostname != domain or not re.fullmatch(r'[A-Za-z0-9.-]+', domain):
        parser.error('--domain must be a hostname without scheme, port or path')
    if not re.fullmatch(r'[A-Za-z0-9.-]+', args.upstream_tls_name):
        parser.error('--upstream-tls-name must be a DNS name')
    if not args.ca_file.is_file():
        parser.error(f'CA bundle does not exist: {args.ca_file}')
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    lines = [
        '# Generated by scripts/nebula-public-endpoint.py',
        'events {}', 'http {', f'  server {{ listen 127.0.0.1:{args.listen};',
        '    server_name _;', '    proxy_http_version 1.1;',
        '    proxy_set_header Host $host;', '    proxy_set_header X-Forwarded-Host $host;',
        '    proxy_set_header X-Forwarded-Proto https;',
        '    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
        '    proxy_set_header Connection "";', '    proxy_buffering off;',
        '    proxy_read_timeout 300s;',
        '    proxy_ssl_verify on;',
        f'    proxy_ssl_trusted_certificate {args.ca_file.resolve()};',
        '    proxy_ssl_server_name on;',
        f'    proxy_ssl_name {args.upstream_tls_name};',
    ]
    for name, port in endpoints():
        lines.extend([f'    location /{name}/ {{', f'      proxy_pass https://127.0.0.1:{port}/;', '    }'])
    lines.extend(['    location / { return 404; }', '  }', '}'])
    nginx = output / 'nginx.conf'
    nginx.write_text('\n'.join(lines) + '\n')
    print(f'Nginx: {nginx}')
    print(f'Run: nginx -t -c {nginx}')
    print(f'Run: nginx -c {nginx}')
    print(f'Run: ngrok http {args.listen} --url https://{domain}')
    for name, _ in endpoints():
        print(f'https://{domain}/{name}/.well-known/agent-card.json')


if __name__ == '__main__':
    main()
